-- Run this SQL in Supabase > SQL Editor.
-- Supabase Auth stores passwords securely; do not create a password column.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  service text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.enquiries enable row level security;

-- Each signed-in user may read only their own profile.
create policy "Users can read own profile" on public.profiles
for select to authenticated using (auth.uid() = id);

-- Create a profile when someone registers.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Anyone can submit an enquiry; only admins can read enquiries.
create policy "Anyone can submit enquiries" on public.enquiries
for insert to anon, authenticated
with check (
  length(trim(name)) between 1 and 120 and
  length(trim(email)) between 3 and 254 and
  length(trim(service)) between 1 and 80 and
  length(trim(message)) between 1 and 5000
);

create policy "Admins can read enquiries" on public.enquiries
for select to authenticated
using (exists (
  select 1 from public.profiles
  where profiles.id = auth.uid() and profiles.is_admin = true
));

